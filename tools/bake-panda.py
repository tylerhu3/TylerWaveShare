#!/usr/bin/env python3
"""Bake the Panda app's home icon from the first frame of panda.gif.

Generates main/assets/app_icon_panda.c (120x120 RGB565A8, circular mask).
The app itself draws Bao with LVGL shapes, so the GIF is no longer embedded.

Requires `ffmpeg` on PATH; uses only Python stdlib.
"""
import math
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_GIF = os.path.join(REPO, "panda.gif")
OUT_DIR = os.path.join(REPO, "main", "assets")

ICON_D = 120


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def emit_panda_icon_c(src_path):
    # Center-crop to square and scale to 120x120 raw RGB24 using ffmpeg
    cmd = [
        "ffmpeg", "-y", "-i", src_path,
        "-frames:v", "1",
        "-vf", f"crop='min(iw,ih)':'min(iw,ih)',scale={ICON_D}:{ICON_D}:flags=lanczos",
        "-f", "rawvideo", "-pix_fmt", "rgb24", "-",
    ]
    rgb = subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL).stdout
    if len(rgb) != ICON_D * ICON_D * 3:
        raise RuntimeError(f"Unexpected icon byte count: {len(rgb)}")

    body = bytearray()
    alpha = bytearray()
    c = (ICON_D - 1) * 0.5
    r_lim = ICON_D * 0.5

    for y in range(ICON_D):
        for x in range(ICON_D):
            idx = (y * ICON_D + x) * 3
            v = rgb565(rgb[idx], rgb[idx + 1], rgb[idx + 2])
            body.append(v & 0xFF)
            body.append((v >> 8) & 0xFF)
            # Smooth 1 px anti-aliased circular mask
            d = math.hypot(x - c, y - c)
            if d <= r_lim - 1.0:
                a = 255
            elif d >= r_lim:
                a = 0
            else:
                a = int(round((r_lim - d) * 255.0))
            alpha.append(a)
    body.extend(alpha)

    lines = [
        "/* Generated by tools/bake-panda.py. Do not edit by hand. */",
        '#include "lvgl.h"',
        "",
        "static const uint8_t app_icon_panda_map[] = {",
    ]
    for i in range(0, len(body), 16):
        chunk = body[i:i + 16]
        lines.append("    " + "".join(f"0x{b:02X}," for b in chunk))
    lines.append("};")
    lines.append(
        f"""
const lv_image_dsc_t app_icon_panda = {{
    .header = {{
        .magic  = LV_IMAGE_HEADER_MAGIC,
        .cf     = LV_COLOR_FORMAT_RGB565A8,
        .flags  = 0,
        .w      = {ICON_D},
        .h      = {ICON_D},
        .stride = {ICON_D * 2},
    }},
    .data_size = sizeof(app_icon_panda_map),
    .data      = app_icon_panda_map,
}};"""
    )
    path = os.path.join(OUT_DIR, "app_icon_panda.c")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"app_icon_panda.c {len(body):7d} B ({len(body) / 1024:.1f} KB)")


def main():
    if not os.path.exists(SRC_GIF):
        sys.exit(f"Missing source GIF: {SRC_GIF}")
    os.makedirs(OUT_DIR, exist_ok=True)
    emit_panda_icon_c(SRC_GIF)
    subprocess.run([sys.executable, os.path.join(REPO, "tools", "sync_cmake.py")], check=True)


if __name__ == "__main__":
    main()
